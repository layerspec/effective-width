"""Supplement table of the layer-local law check (2026-09-26): for a random-initialised network, per dense
convolution, the measured k*(tau) of the conv output against the law of W~ Sigma_patch W~^T evaluated by
sampling (mean +- SD over draws) and, for the bulk, by Silverstein's equation.  Reads results/freeprob/*.csv.

    python scripts/freeprob_table.py --results ../results --out ../paper/table_freeprob.tex
"""
from __future__ import annotations

import argparse
import os

import pandas as pd

NAMES = {"vgg16_bn_random": "VGG-16 (BN)", "resnet18_random": "ResNet-18"}


def render(tables: dict[str, pd.DataFrame]) -> str:
    out = ["% Generated by scripts/freeprob_table.py.  Do not edit by hand.",
           "\\begin{tabular}{@{}lrrr rrr rrr@{}}", "\\toprule",
           " & & & & \\multicolumn{3}{c}{$k^*(0.95)$} & \\multicolumn{3}{c}{$k^*(0.999)$} \\\\",
           "\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}",
           "Layer & $C$ & $d$ & $r_{\\max}$ & measured & law & Silverstein & measured & law & Silverstein \\\\", "\\midrule"]
    for i, (name, df) in enumerate(tables.items()):
        if i:
            out.append("\\midrule")
        out.append(f"\\multicolumn{{10}}{{@{{}}l}}{{\\emph{{{name}}}}} \\\\")
        for _, r in df.sort_values("depth_index").iterrows():
            lay = str(r.layer).replace("_", "\\_")
            out.append(f"{lay} & {int(r.C)} & {int(r.d)} & {int(r.r_max)} & {r.measured_95:.0f} & {r.mc_95:.1f} $\\pm$ {r.mc_sd_95:.1f} & {int(r.silverstein_95)} "
                       f"& {r.measured_999:.0f} & {r.mc_999:.1f} $\\pm$ {r.mc_sd_999:.1f} & {int(r.silverstein_999)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="../results")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    tables = {}
    for stem, name in NAMES.items():
        f = os.path.join(a.results, "freeprob", stem + ".csv")
        if os.path.exists(f):
            tables[name] = pd.read_csv(f)
    tex = render(tables)
    if a.out:
        open(a.out, "w").write(tex); print("wrote", a.out)
    else:
        print(tex)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

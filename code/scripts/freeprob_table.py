"""Supplement table of the layer-local law check (2026-09-26): for a random-initialised network, per dense
convolution, the measured k*(tau) of the conv output against the law of W~ Sigma_patch W~^T evaluated by
sampling (mean +- SD over draws) and, for the bulk, by Silverstein's equation.  Reads results/freeprob/*.csv.

    python scripts/freeprob_table.py --results ../results --out ../paper/table_freeprob.tex
"""
from __future__ import annotations

import argparse
import os

import pandas as pd

NAMES = {"vgg16_bn_random": "VGG-16 (BN)", "resnet18_random": "ResNet-18"}
ALL = {"vgg16_bn_random": "VGG-16 (BN)", "resnet18_random": "ResNet-18", "resnet34.tv_in1k_random": "ResNet-34",
       "resnet50_random": "ResNet-50", "resnet101.tv_in1k_random": "ResNet-101", "wide_resnet50_2.tv_in1k_random": "Wide-ResNet-50-2",
       "resnext50_32x4d.tv_in1k_random": "ResNeXt-50", "densenet121.tv_in1k_random": "DenseNet-121",
       "mobilenetv2_100.ra_in1k_random": "MobileNetV2", "mobilenetv3_large_100.ra_in1k_random": "MobileNetV3-L",
       "efficientnet_b0.ra_in1k_random": "EfficientNet-B0"}


def render_summary(tables: dict[str, pd.DataFrame]) -> str:
    """One row per family and tau: layers, median and max |law - measured| in channels and in k*/r_max, the share of
    layers within 0.05 r_max, the share within twice the law's own SD (plus one channel), Spearman."""
    out = ["% Generated by scripts/freeprob_table.py --summary.  Do not edit by hand.",
           "\\begin{tabular}{@{}lrrrrrrrr@{}}", "\\toprule",
           "Family & $\\tau$ & $L$ & med.\\ $|\\Delta|$ (ch) & max & med.\\ $|\\Delta|/r_{\\max}$ & within $0.05$ & within 2 SD & $\\rho$ \\\\", "\\midrule"]
    for name, df in tables.items():
        for tk, tau in (("95", "0.95"), ("999", "0.999")):
            dm = (df[f"mc_{tk}"] - df[f"measured_{tk}"]).abs(); rel = dm / df.r_max
            w05 = (rel <= 0.05).mean(); wsd = (dm <= 2 * df[f"mc_sd_{tk}"] + 1).mean()
            rho = df[f"mc_{tk}"].corr(df[f"measured_{tk}"], method="spearman")
            lab = name if tk == "95" else ""
            out.append(f"{lab} & {tau} & {len(df)} & {dm.median():.1f} & {dm.max():.0f} & {rel.median():.3f} & {100 * w05:.0f}\\% & {100 * wsd:.0f}\\% & {rho:.3f} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"



def render(tables: dict[str, pd.DataFrame]) -> str:
    out = ["% Generated by scripts/freeprob_table.py.  Do not edit by hand.",
           "\\begin{tabular}{@{}lrrr rrr rrr@{}}", "\\toprule",
           " & & & & \\multicolumn{3}{c}{$k^*(0.95)$} & \\multicolumn{3}{c}{$k^*(0.999)$} \\\\",
           "\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}",
           "Layer & $C$ & $d$ & $r_{\\max}$ & measured & law & Silverstein & measured & law & Silverstein \\\\", "\\midrule"]
    for i, (name, df) in enumerate(tables.items()):
        if i:
            out.append("\\midrule")
        out.append(f"\\multicolumn{{10}}{{@{{}}l}}{{\\emph{{{name}}}}} \\\\")
        for _, r in df.sort_values("depth_index").iterrows():
            lay = str(r.layer).replace("_", "\\_")
            out.append(f"{lay} & {int(r.C)} & {int(r.d)} & {int(r.r_max)} & {r.measured_95:.0f} & {r.mc_95:.1f} $\\pm$ {r.mc_sd_95:.1f} & {int(r.silverstein_95)} "
                       f"& {r.measured_999:.0f} & {r.mc_999:.1f} $\\pm$ {r.mc_sd_999:.1f} & {int(r.silverstein_999)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="../results")
    ap.add_argument("--out", default=None)
    ap.add_argument("--summary", action="store_true", help="one row per family and tau over every results/freeprob/*.csv")
    a = ap.parse_args(argv)
    tables = {}
    for stem, name in (ALL if a.summary else NAMES).items():
        f = os.path.join(a.results, "freeprob", stem + ".csv")
        if os.path.exists(f):
            tables[name] = pd.read_csv(f)
    tex = render_summary(tables) if a.summary else render(tables)
    if a.out:
        open(a.out, "w").write(tex); print("wrote", a.out)
    else:
        print(tex)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
